CHAR_DIMS = ["形体与解剖", "面部与表情", "表演与动作"]
KEYS = {"binary": {"0", "100"}, "discrete": {"0", "50", "100"}}


def main(spec_path, out):
    spec = json.load(open(spec_path, encoding="utf-8-sig"))
    crit, errs = [], []
    for i, it in enumerate(spec["items"], 1):
        dim, st = it["dimension"], it["type"]
        an = it.get("anchors") or DEFAULT.get(dim)
        if not an:
            errs.append(f"“{dim}”没有锚点，也没有内置的默认锚点")
            continue
        if st not in KEYS or set(an) != KEYS[st]:
            errs.append(f"“{dim}”的锚点和类型 {st} 对不上")
        if it["weight"] <= 0:
            errs.append(f"“{dim}”的权重要为正数")
        crit.append({"criterion_id": f"R{i:02d}", "dimension": dim, "criterion": it["criterion"],
                     "weight": it["weight"], "critical": bool(it["critical"]),
                     "pass_threshold": 100 if it["critical"] else None,
                     "scoring_type": st, "score_anchors": an})
    total = sum(c["weight"] for c in crit)
    if total != 100:
        errs.append(f"权重合计是 {total}，要是 100")
    dims = {c["dimension"]: c for c in crit}
    for d in CHAR_DIMS:
        if d not in dims or not dims[d]["critical"]:
            errs.append(f"缺少人物关键项“{d}”，或它不是关键项")
    if errs:
        for e in errs:
            print("ERROR", e)
        sys.exit(1)
    r = {"task": spec["task"], "scoring_policy": {"aggregation": "weighted_sum", "total_weight": 100,
                                                  "total_threshold": 85, "require_all_critical_pass": True},
         "criteria": crit}
    s = json.dumps(r, ensure_ascii=False, indent=2) + "\n"
    if "\ufffd" in s:
        print("ERROR 内容里有乱码字符 U+FFFD")
        sys.exit(1)
    open(out, "w", encoding="utf-8").write(s)
    print(f"{out}：{len(crit)} 项，权重合计 100")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    main(sys.argv[1], sys.argv[2])
